const { contextBridge, ipcRenderer } = require('electron');

const on = (channel) => (fn) => {
  const handler = (_e, payload) => fn(payload);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
};

contextBridge.exposeInMainWorld('startbar', {
  getState: () => ipcRenderer.invoke('state'),
  onState: on('state'),
  onMenuState: on('menu:state'),
  onBarPlace: on('bar:place'),
  onMenuShown: on('menu:shown'),
  clickStart: () => ipcRenderer.send('bar:start'),
  barMenu: () => ipcRenderer.send('bar:menu'),
  hideMenu: () => ipcRenderer.send('menu:hide'),
  apps: () => ipcRenderer.invoke('menu:apps'),
  placeIcons: () => ipcRenderer.invoke('menu:placeIcons'),
  userPicture: () => ipcRenderer.invoke('menu:userPicture'),
  recent: () => ipcRenderer.invoke('menu:recent'),
  launch: (appPath) => ipcRenderer.send('menu:launch', appPath),
  appMenu: (appPath, fromRecent) => ipcRenderer.send('menu:appMenu', appPath, fromRecent),
  onRecentChanged: on('menu:recentChanged'),
  searchFiles: (q) => ipcRenderer.invoke('menu:files', q),
  openFile: (file) => ipcRenderer.send('menu:openFile', file),
  openFolder: (folder) => ipcRenderer.send('menu:openFolder', folder),
  open: (target) => ipcRenderer.send('menu:open', target),
  power: (action) => ipcRenderer.send('menu:power', action),
  updateSettings: (patch) => ipcRenderer.invoke('settings:update', patch),
  resetSettings: () => ipcRenderer.send('settings:reset'),
  resetThemeSettings: () => ipcRenderer.send('settings:resetTheme'),
  openLink: (name) => ipcRenderer.send('settings:link', name),
  askPermission: (name) => ipcRenderer.send('access:ask', name),
  launchPin: (appPath) => ipcRenderer.send('pins:launch', appPath),
  pinMenu: (appPath) => ipcRenderer.send('pins:menu', appPath),
  setPins: (list) => ipcRenderer.send('pins:set', list),
  unpin: (appPath) => ipcRenderer.send('pins:remove', appPath),
  addPins: () => ipcRenderer.send('pins:add'),
  setDockHidden: (hide) => ipcRenderer.send('dock:hidden', hide),
  moveDockToBottom: () => ipcRenderer.send('dock:bottom'),
  addFolders: () => ipcRenderer.send('folders:add'),
  setFolders: (list) => ipcRenderer.send('folders:set', list),
  addKeepRunning: () => ipcRenderer.send('keepRunning:add'),
  setKeepRunning: (list) => ipcRenderer.send('keepRunning:set', list),
  setLoginItem: (on) => ipcRenderer.send('login:set', on),
  checkUpdates: () => ipcRenderer.send('updates:check'),
  copyText: (text) => ipcRenderer.send('clipboard:text', text),
  exportSettings: () => ipcRenderer.send('settings:export'),
  importSettings: () => ipcRenderer.send('settings:import'),
  onSettingsPage: on('settings:page'),
  pauseShortcut: () => ipcRenderer.send('shortcut:pause'),
  resumeShortcut: () => ipcRenderer.send('shortcut:resume'),
  getTasks: () => ipcRenderer.invoke('tasks:get'),
  onTasks: on('tasks'),
  taskCommand: (command) => ipcRenderer.invoke('tasks:command', command),
  taskIcons: (paths) => ipcRenderer.invoke('tasks:icons', paths),
  taskMenu: (target) => ipcRenderer.send('tasks:menu', target),
  ungroup: (id) => ipcRenderer.send('tasks:ungroup', id),
  regroup: (id) => ipcRenderer.send('tasks:regroup', id),
  setOrder: (keys) => ipcRenderer.send('tasks:order', keys),
  putAllBack: () => ipcRenderer.send('tasks:putAllBack'),
  dragOut: (d) => ipcRenderer.send('tasks:dragOut', d),
  onDragOver: on('tasks:dragOver'),
  showTip: (tip) => ipcRenderer.send('tip:show', tip),
  hideTip: () => ipcRenderer.send('tip:hide'),
  onTipText: on('tip:text'),
  tipSize: (size) => ipcRenderer.send('tip:size', size),
  showPreview: (payload) => ipcRenderer.send('preview:show', payload),
  pinPreview: (payload) => ipcRenderer.send('preview:pin', payload),
  leavePreview: () => ipcRenderer.send('preview:leave'),
  hidePreview: () => ipcRenderer.send('preview:hide'),
  previewHover: (on) => ipcRenderer.send('preview:hover', on),
  previewPeek: (id) => ipcRenderer.send('preview:peek', id), // null puts things back
  previewSize: (size) => ipcRenderer.send('preview:size', size),
  onPreviewShow: on('preview:show'),
  onPreviewImage: on('preview:image'),
  showGroup: (group) => ipcRenderer.send('group:show', group),
  hideGroup: () => ipcRenderer.send('group:hide'),
  onGroupShow: on('group:show'),
  groupSize: (size) => ipcRenderer.send('group:size', size),
  clockClick: (rect) => ipcRenderer.send('clock:click', rect),
  onCalendarShow: on('calendar:show'),
  calendarSize: (size) => ipcRenderer.send('calendar:size', size),
  hideCalendar: () => ipcRenderer.send('calendar:hide'),
  getStatus: () => ipcRenderer.invoke('status:get'),
  onStatus: on('status'),
  trayClick: (kind, rect) => ipcRenderer.send('tray:click', { kind, rect }),
  trayCommand: (command) => ipcRenderer.send('tray:command', command),
  traySettings: (name) => ipcRenderer.send('tray:settings', name),
  onPopoverShow: on('popover:show'),
  popoverSize: (size) => ipcRenderer.send('popover:size', size),
  hidePopover: () => ipcRenderer.send('popover:hide')
});
